alter table public.terminology_seed_catalog enable row level security;
revoke all on public.terminology_seed_catalog from public, anon, authenticated;

create table public.terminology_claims (
  seed_id text primary key references public.terminology_seed_catalog(id),
  id uuid not null unique default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  claimed_at timestamptz not null default now()
);
alter table public.terminology_claims enable row level security;
revoke all on public.terminology_claims from public, anon, authenticated;

create function public.list_terminology_claims()
returns table(seed_id text, id uuid, owner_id uuid, display_name text, claimed_at timestamptz)
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null or not exists(select 1 from profiles where profiles.id=auth.uid()) then
    raise exception 'Profile required' using errcode='42501';
  end if;
  return query select c.seed_id,c.id,c.owner_id,p.display_name,c.claimed_at
    from terminology_claims c join profiles p on p.id=c.owner_id order by c.seed_id;
end $$;

create function public.claim_terminology_term(term_id text) returns uuid
language plpgsql security definer set search_path = public as $$
declare claim_id uuid;
begin
  if auth.uid() is null or not (has_role('reviewer') or has_role('editor')) then
    raise exception 'Scholar role required' using errcode='42501';
  end if;
  insert into terminology_claims(seed_id,owner_id) values(term_id,auth.uid()) returning id into claim_id;
  insert into audit_logs(actor_id,action,record_id,details)
    values(auth.uid(),'terminology_claimed',claim_id,jsonb_build_object('seed_id',term_id));
  return claim_id;
end $$;

create function public.release_terminology_claim(term_id text, claim_id uuid) returns void
language plpgsql security definer set search_path = public as $$
declare removed uuid;
begin
  if auth.uid() is null then raise exception 'Sign in required' using errcode='42501'; end if;
  delete from terminology_claims where seed_id=term_id and id=claim_id and owner_id=auth.uid() returning id into removed;
  if removed is null then raise exception 'Claim changed or not yours' using errcode='42501'; end if;
  insert into audit_logs(actor_id,action,record_id,details)
    values(auth.uid(),'terminology_released',removed,jsonb_build_object('seed_id',term_id));
end $$;

revoke execute on function public.list_terminology_claims() from public, anon;
revoke execute on function public.claim_terminology_term(text) from public, anon;
revoke execute on function public.release_terminology_claim(text,uuid) from public, anon;
grant execute on function public.list_terminology_claims() to authenticated;
grant execute on function public.claim_terminology_term(text) to authenticated;
grant execute on function public.release_terminology_claim(text,uuid) to authenticated;

